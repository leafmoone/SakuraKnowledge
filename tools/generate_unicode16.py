"""Generate complete Unicode-16 reference tables from CPython's UCD.

Build-time only; Rust runtime has no Python dependency. No handpicked folds.
Assigned-codepoint ranges allow newer normalization libraries to preserve
Unicode-16 unassigned characters as normalization boundaries (CCC=0).
"""
import argparse
import unicodedata
from pathlib import Path


def ranges(predicate):
    result = []
    start = end = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if predicate(chr(cp)):
            if end is not None and cp == end + 1:
                end = cp
            else:
                if start is not None:
                    result.append((start, end))
                start = end = cp
    if start is not None:
        result.append((start, end))
    return result


def generate():
    if unicodedata.unidata_version != "16.0.0":
        raise RuntimeError("generator requires CPython Unicode 16.0.0")
    lines = ["// Generated by tools/generate_unicode16.py; do not hand-edit.",
             'pub const VERSION: &str = "16.0.0";',
             "pub static FOLD: &[(u32, &str)] = &["]
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        folded = char.casefold()
        if char != folded:
            escaped = "".join(f"\\u{{{ord(c):x}}}" for c in folded)
            lines.append(f'    (0x{cp:x}, "{escaped}"),')
    lines.append("];")
    for name, predicate in (("ALNUM", str.isalnum),
                            ("ASSIGNED", lambda c: unicodedata.category(c) != "Cn")):
        lines.append(f"pub static {name}: &[(u32, u32)] = &[")
        for start, end in ranges(predicate):
            lines.append(f"    (0x{start:x}, 0x{end:x}),")
        lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if args.out.read_text(encoding="utf-8") != text:
            raise SystemExit("Unicode tables differ")
    else:
        with args.out.open("x", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
